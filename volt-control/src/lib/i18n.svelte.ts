const dicts: Record<Lang, Dict> = { 'zh-CN': zhCN, 'zh-TW': zhTW, en, ja }

/** Language in effect; reading it inside `t` makes every caller reactive. */
export const i18n = $state({ lang: 'zh-CN' as Lang })

export function t(key: Key, args?: Record<string, string | number>): string {
  let s = dicts[i18n.lang][key]
  if (args) for (const [k, v] of Object.entries(args)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

/** Applies the language the backend resolved (also drives per-language fonts in app.css). */
export function applyLang(lang: Lang) {
  i18n.lang = lang
  document.documentElement.lang = lang
}
